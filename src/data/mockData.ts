export function calculateDTB(tx1: number | null, tx2: number | null, tx3: number | null, gk: number | null, ck: number | null): number | null {
  const txScores = [tx1, tx2, tx3].filter((s): s is number => s !== null && !isNaN(s));
  if (txScores.length === 0 && gk === null && ck === null) return null;
  
  // Trọng số theo Thông tư Bộ GD&ĐT:
  // ĐTB = (Tổng điểm TX + 2*GK + 3*CK) / (Số bài TX + 2 + 3)
  const sumTX = txScores.reduce((acc, curr) => acc + curr, 0);
  const countTX = txScores.length;

  let totalPoints = sumTX;
  let totalWeight = countTX;

  if (gk !== null) {
    totalPoints += gk * 2;
    totalWeight += 2;
  }
  if (ck !== null) {
    totalPoints += ck * 3;
    totalWeight += 3;
  }

  if (totalWeight === 0) return null;
  return Math.round((totalPoints / totalWeight) * 10) / 10;
}

export function calculateRank(dtb: number | null): AcademicRank {
  if (dtb === null) return 'Chưa đạt';
  if (dtb >= 8.5) return 'Xuất sắc';
  if (dtb >= 8.0) return 'Giỏi';
  if (dtb >= 6.5) return 'Khá';
  if (dtb >= 5.0) return 'Đạt';
  return 'Chưa đạt';
}

